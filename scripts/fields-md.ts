// Renders docs/FIELDS.md from docs/fields.json, the single source for what every dataset, file and
// field in an export means. Run plainly (npm run fields), it writes FIELDS.md; with --check it exits 1
// when FIELDS.md differs from what it would write. FIELDS.md is never edited by hand.
import { existsSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const FIELDS_JSON = fileURLToPath(new URL('../docs/fields.json', import.meta.url));
export const FIELDS_MD = fileURLToPath(new URL('../docs/FIELDS.md', import.meta.url));
export const HEADER = '<!-- Generated from docs/fields.json by scripts/fields-md.ts (npm run fields). Do not edit this file by hand. -->';

interface Based { basis: string; from?: string; sources?: string[] }
interface AboutLine extends Based { text: string }
interface Field extends Based { path: string; type: string; meaning: string; optional?: boolean; covers?: boolean }
interface FileEntry { path: string; title: string; datasets: string[]; about: AboutLine[]; fields: Field[]; sources: string[] }
interface Dataset { id: string; title: string; state: string; needsPrivate: string; about: AboutLine[]; files: string[]; manifestSources: string[]; sources: string[] }
interface Line { id: string; title: string; about: AboutLine[]; printedBy: { command: string; where: string }[]; parts: Field[]; sources: string[] }
export interface FieldsJson {
  format: number; title: string; about: string[];
  bases: { id: string; label: string; about: string }[];
  statuses: { status: string; meaning: string }[];
  datasets: Dataset[]; files: FileEntry[]; lines: Line[];
}

const isUrl = (s: string) => /^https?:\/\//.test(s);

// R13: each basis id shows as one fixed phrase.
export function basisPhrase(b: Based): string {
  switch (b.basis) {
    case 'code': return "from castsnap's code";
    case 'app': return "the app's own description";
    case 'inferred':
      if (!b.from) throw new Error('an inferred basis needs its from');
      return `inferred from ${b.from}`;
    case 'docs': {
      const url = (b.sources ?? []).find(isUrl);
      if (!b.from || !url) throw new Error('a docs basis needs its from and a link');
      return `[${b.from}](${url})`;
    }
    case 'unknown':
      if (!b.from) throw new Error('an unknown basis needs its from');
      return `meaning unknown (${b.from})`;
    default: throw new Error(`unknown basis id ${b.basis}`);
  }
}

const cell = (s: string) => s.replace(/\|/g, '\\|');
const source = (s: string) => (isUrl(s) ? `[link](${s})` : `\`${s}\``);
const sourceList = (xs: string[] | undefined) => (xs ?? []).map(source).join(', ');
const aboutLines = (xs: AboutLine[]) => xs.map((a) => `- ${a.text} (Basis: ${basisPhrase(a)})`);

// GitHub's heading anchors: lower case, punctuation other than - and _ dropped, spaces to hyphens,
// and -1, -2 … on repeats.
function slugger() {
  const seen = new Map<string, number>();
  return (heading: string) => {
    const base = heading.replace(/`/g, '').toLowerCase().replace(/[^\p{L}\p{N} _-]/gu, '').replace(/ /g, '-');
    const n = seen.get(base) ?? 0;
    seen.set(base, n + 1);
    return n ? `${base}-${n}` : base;
  };
}

function fieldTable(first: string, fields: Field[]): string[] {
  if (!fields.length) return ['No fields are described: see the lines above.'];
  const rows = fields.map((f) => {
    const type = `${f.type}${f.optional ? ', optional' : ''}`;
    const meaning = `${f.meaning}${f.covers ? ' (This covers everything under it.)' : ''}`;
    return `| \`${cell(f.path)}\` | ${cell(type)} | ${cell(meaning)} | ${cell(basisPhrase(f))} | ${cell(sourceList(f.sources))} |`;
  });
  return [`| ${first} | Type | Meaning | Basis | Sources |`, '| --- | --- | --- | --- | --- |', ...rows];
}

export function renderFieldsMd(j: FieldsJson = JSON.parse(readFileSync(FIELDS_JSON, 'utf8')) as FieldsJson): string {
  if (j.format !== 1) throw new Error(`fields.json format ${j.format} is not 1`);
  const slug = slugger();
  const out: string[] = [HEADER, '', `# ${j.title}`, ''];
  slug(j.title);
  for (const p of j.about) out.push(p, '');
  out.push('## Contents', '', '- [Bases](#bases)', '- [Statuses](#statuses)', '- [Datasets](#datasets)', '- [Files](#files)', '- [Printed lines](#printed-lines)', '');
  for (const h of ['Contents', 'Bases', 'Statuses', 'Datasets', 'Files', 'Printed lines']) slug(h);

  out.push('## Bases', '', 'Each description ends with its basis: where its meaning comes from.', '');
  for (const b of j.bases) out.push(`- **${b.label}** (\`${b.id}\`): ${b.about}`);
  out.push('');

  out.push('## Statuses', '', '| Status | Meaning |', '| --- | --- |');
  for (const s of j.statuses) out.push(`| \`${cell(s.status)}\` | ${cell(s.meaning)} |`);
  out.push('');

  // Anchors are assigned in document order: datasets, then files, then lines.
  const dsHeads = j.datasets.map((d) => `### ${d.id}. ${d.title}`);
  for (const h of dsHeads) slug(h.slice(4));
  const fileHeads = j.files.map((f) => `### \`${f.path}\``);
  const fileSlug = new Map(j.files.map((f, i) => [f.path, slug(fileHeads[i].slice(4))]));

  out.push('## Datasets', '');
  j.datasets.forEach((d, i) => {
    out.push(dsHeads[i], '', `State: ${d.state}. Needs --private: ${d.needsPrivate}.`, '', ...aboutLines(d.about), '');
    if (d.files.length) {
      out.push('Files:', '');
      for (const f of d.files) out.push(`- ${fileSlug.has(f) ? `[\`${f}\`](#${fileSlug.get(f)})` : `\`${f}\``}`);
      out.push('');
    }
    if (d.manifestSources.length) out.push(`Sources in manifest.json: ${d.manifestSources.map((s) => `\`${s}\``).join(', ')}.`, '');
    out.push(`Sources: ${sourceList(d.sources)}.`, '');
  });

  out.push('## Files', '');
  j.files.forEach((f, i) => {
    out.push(fileHeads[i], '', `${f.title}. Datasets: ${f.datasets.length ? f.datasets.join(', ') : 'none'}.`, '', ...aboutLines(f.about), '', ...fieldTable('Field', f.fields), '', `Sources: ${sourceList(f.sources)}.`, '');
  });

  out.push('## Printed lines', '');
  for (const l of j.lines) {
    slug(l.title);
    out.push(`### ${l.title}`, '', 'Printed by:', '');
    for (const p of l.printedBy) out.push(`- ${p.command}: ${p.where}`);
    out.push('', ...aboutLines(l.about), '', ...fieldTable('Part', l.parts), '', `Sources: ${sourceList(l.sources)}.`, '');
  }
  return out.join('\n').replace(/\n+$/, '\n');
}

if (process.argv[1] && realpathSync(fileURLToPath(import.meta.url)) === realpathSync(process.argv[1])) {
  const md = renderFieldsMd();
  if (process.argv.includes('--check')) {
    const cur = existsSync(FIELDS_MD) ? readFileSync(FIELDS_MD, 'utf8').replace(/\r\n/g, '\n') : null;
    if (cur !== md) {
      console.error('docs/FIELDS.md is out of date: run npm run fields');
      process.exit(1);
    }
    console.log('docs/FIELDS.md is up to date');
  } else {
    writeFileSync(FIELDS_MD, md);
    console.log('wrote docs/FIELDS.md');
  }
}
